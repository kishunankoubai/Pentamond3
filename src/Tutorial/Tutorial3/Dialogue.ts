import type { Tutorial3Board } from "./Board";
import type { TutorialControlMarkup } from "../TutorialTypes";

/** 応用などの説明文。教習の進行・盤面操作はSceneTutorialが担当する。 */
export function tutorial3Introduction(model: Tutorial3Board, controlMarkup: TutorialControlMarkup): string[] {
    switch (model.lesson.id) {
        case "next":
            return [
                "盤面の右側にあるNEXTを見てみましょう。これから出現するモンドが上から順番に並んでいます。",
                "今のモンドだけでなく次に来る形も見ておくと置き場所を考えやすくなります。",
                "NEXTの一番上の形を確かめてから今のモンドを黄色の枠に設置しましょう。予告と出現する形を見比べながら4個設置してみましょう。",
            ];
        case "holdReset":
            return [
                "Pentamondには上へ移動する操作はありません。なので下へ動かしすぎたときに困ってしまいます。こんなときはホールドを2回しましょう！",
                "ホールドにすでにモンドがあるときに2回入れ替えると元のモンドに戻ります。入れ替えたモンドは初期位置・初期の向きで出現します。",
                `それでは${controlMarkup("move-down")}で下へ動かし${controlMarkup("hold")}で2回ホールドしてみましょう。`,
            ];
        case "juggling":
            return [
                "今のモンドもホールドのモンドも都合が悪いとき、ネクストを取り出す「ジャグリング」というテクニックがあります。",
                "設置、ホールド、一手戻し、ホールドの順番で行うと、なんやかんやあって次に出現する予定のモンドを取り出すことができます！",
                "一手戻しを使うためサバイバルでは持ち時間が3減ってしまいますが、うまく使えば活用できて便利です。",
                `まず${controlMarkup("put")}で設置し、右の課題に沿って順番に操作しましょう。最後に、取り出したモンドを黄色の枠に設置してください。`,
            ];
        case "rotation":
            return [
                "屋根の下などには滑り移動したあとに回転すると入る形があります。いわゆる「回転入れ」です。",
                `まず2回左回転して形を変え、${controlMarkup("move-down")}で滑り込んでみてください。そのあと2回右回転してみましょう。`,
                "滑り移動だけではなく、滑ったあとに回転してから設置することがポイントです。",
            ];
        case "leftPriority":
            return [
                "下方向の入力ではまず真下へ進もうとします。真下に進めない場合には左下、右下の順に滑れるかを調べます。",
                "つまり、左右のどちらにも滑れるときは左が優先されます。今回は灰色の三角形の左右がどちらも空いています。",
                `実際に${controlMarkup("move-down")}で下へ進んでみましょう。左へ滑ったら黄色の枠の位置に設置してください。`,
            ];
        case "blockedSpawn":
            return [
                "地形が高くなり初期位置にモンドが出現しなくなることがあります。その間は移動・回転・設置・ホールドができません。",
                "しかし、これで終わりではありません。一手戻しをするか一番下の列の消去で出現する場所を作れます。",
                `まずは${controlMarkup("put")}でそのまま設置し、次のモンドが出現できない場面を見てみましょう。`,
            ];
    }
}
